package server_test

import (
	"encoding/base64"
	"fmt"
	"os"
	"strings"
	"testing"
	"time"

	"github.com/hejmo-home/hejmo/internal/calendar"
	"github.com/hejmo-home/hejmo/internal/familyview"
	"github.com/hejmo-home/hejmo/internal/i18n"
	"github.com/hejmo-home/hejmo/internal/server"
	"github.com/hejmo-home/hejmo/web"
)

// TestWriteDesignPreview writes the self-contained preview page for the
// product owner's approval of ticket 5.3. It renders the real view model with
// the real template for the example family; nothing is hand-written HTML.
// Run: HEJMO_WRITE_PREVIEW=../../docs/design/preview-23.html go test ./internal/server -run WriteDesignPreview
func TestWriteDesignPreview(t *testing.T) {
	t.Parallel()
	out := os.Getenv("HEJMO_WRITE_PREVIEW")
	if out == "" {
		t.Skip("set HEJMO_WRITE_PREVIEW to the output path to write the preview")
	}
	css, err := web.Static.ReadFile("static/hejmo.css")
	if err != nil {
		t.Fatal(err)
	}
	font, err := web.Static.ReadFile("static/fonts/Figtree-wght.ttf")
	if err != nil {
		t.Fatal(err)
	}
	style := strings.Replace(string(css), `url("/static/fonts/Figtree-wght.ttf")`, "url(data:font/ttf;base64,"+base64.StdEncoding.EncodeToString(font)+")", 1)

	d := func(day, h, m int) time.Time { return time.Date(2026, 11, day, h, m, 0, 0, berlinTZ) }
	people := []familyview.Person{
		{ID: "mama", Name: "Mama", Slot: 1, Shape: "circle-filled"}, {ID: "papa", Name: "Papa", Slot: 2, Shape: "circle-empty"},
		{ID: "seb", Name: "Sebastian", Slot: 3, Shape: "square-filled"}, {ID: "mia", Name: "Mia", Slot: 4, Shape: "square-empty"}}
	occ := func(title string, s, e time.Time, who ...string) calendar.Occurrence {
		return calendar.Occurrence{EventID: title, CalendarID: "c", Title: title, Start: s, End: e, People: who}
	}
	occs := []calendar.Occurrence{
		occ("Dentist", d(1, 9, 0), d(1, 10, 0), "mama"),
		occ("Team meeting", d(1, 10, 0), d(1, 11, 0), "papa"),
		occ("Football", d(1, 15, 0), d(1, 16, 30), "seb", "mia"),
		occ("Pick up Mia", d(1, 16, 45), d(1, 17, 15), "papa"),
		occ("Family lunch", d(1, 12, 30), d(1, 14, 0)),
		{EventID: "trip", CalendarID: "c", Title: "Grandparents visit", AllDay: true, Start: time.Date(2026, 10, 31, 0, 0, 0, 0, berlinTZ), End: d(3, 0, 0), People: []string{"mama", "papa"}},
		occ("Dentist check-up", d(2, 9, 0), d(2, 9, 45), "mama"),
		occ("Piano", d(2, 15, 0), d(2, 16, 0), "mia"),
		occ("Swimming", d(2, 16, 30), d(2, 17, 30), "seb"),
		occ("Parents' evening", d(2, 19, 0), d(2, 20, 30)),
	}
	build := func(now time.Time, filled, showTomorrow bool) familyview.View {
		v := familyview.Build(familyview.Input{I18n: i18n.MustLoad(), Now: now, Lang: "en", Region: "DE-BY", People: people, Occurrences: occs, ShowTomorrow: showTomorrow})
		if filled {
			// Slots filled for illustration: the data arrives with package 6 (6.4, 6.6, 6.7).
			v.Columns[0].Progress = &familyview.Progress{Done: 3, Total: 5}
			v.Columns[2].Progress = &familyview.Progress{Done: 1, Total: 3}
			v.Columns[3].Progress = &familyview.Progress{Done: 2, Total: 2}
			v.Meal = &familyview.MealTile{Label: "Dinner", Entries: []familyview.MealEntry{{Mealtime: "dinner", Dish: "Pasta bake"}}}
			v.TomorrowTile = &familyview.Tile{Label: "Tomorrow", Lines: []familyview.Line{{Kind: familyview.LineWaste, Text: "Paper bin"}, {Kind: familyview.LineWaste, Text: "Residual waste"}}, Alert: now.Hour() >= 18}
		}
		return v
	}
	var body strings.Builder
	frame := func(caption, theme string, w, h int, v familyview.View) {
		html, err := server.RenderFamilyView("en", v)
		if err != nil {
			t.Fatal(err)
		}
		fmt.Fprintf(&body, `<figure><figcaption>%s (%dx%d)</figcaption><div class="frame" data-theme="%s" style="width:%dpx;height:%dpx">%s</div></figure>`+"\n", caption, w, h, theme, w, h, html)
	}
	evening := build(d(1, 18, 5), true, true)
	eveningOff := build(d(1, 18, 5), true, false)
	morning := build(d(1, 7, 58), false, true)
	body.WriteString("<h2>Landscape, evening, display setting \"show tomorrow block\" ON (the block is faded; progress bars and footer tiles filled for illustration)</h2><div class=\"row\">\n")
	frame("Light", "light", 1024, 768, evening)
	frame("Dark", "dark", 1024, 768, evening)
	frame("Black and white", "bw", 1024, 768, evening)
	body.WriteString("</div><h2>Landscape, same evening, setting OFF (the default): nothing of tomorrow is shown</h2><div class=\"row\">\n")
	frame("Light", "light", 1024, 768, eveningOff)
	frame("Black and white", "bw", 1024, 768, eveningOff)
	body.WriteString("</div><h2>Portrait (setting on)</h2><div class=\"row\">\n")
	frame("Light", "light", 768, 1024, evening)
	frame("Dark", "dark", 768, 1024, evening)
	frame("Black and white", "bw", 768, 1024, evening)
	body.WriteString("</div><h2>Morning (the setting is on, but before 18:00 there is no tomorrow block): no tomorrow block, no progress bars, no footer, no weather chip</h2><div class=\"row\">\n")
	frame("Light", "light", 1024, 768, morning)
	body.WriteString("</div>\n")

	page := `<!doctype html>
<!-- Generated by TestWriteDesignPreview from the real view model and template (ticket 5.3). The stylesheet and font are inlined copies of web/static and do not follow later changes. -->
<html lang="en"><head><meta charset="utf-8"><title>Hejmo preview 5.3 family view</title>
<style>` + style + `
body{padding:16px;background:#888;font-family:Figtree,system-ui,sans-serif}
body > h1,body > h2{color:#fff}body > h1{font-size:22px}body > h2{font-size:18px;margin:20px 0 8px}
figure{margin:0 0 28px}figcaption{color:#fff;margin-bottom:6px;font-weight:700}
.row{display:flex;flex-wrap:wrap;gap:24px;align-items:flex-start}
.frame{background:var(--background);color:var(--text);padding:var(--margin);overflow:hidden;box-sizing:border-box}
.frame .fv{height:100%}
</style></head><body>
<h1>Hejmo 5.3 family view: preview with the example family (Mama, Papa, Sebastian, Mia), Sunday 01/11/2026 (All Saints' Day in Bavaria)</h1>
` + body.String() + `</body></html>
`
	if err := os.WriteFile(out, []byte(page), 0o644); err != nil {
		t.Fatal(err)
	}
}
