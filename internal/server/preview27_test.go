package server_test

import (
	"encoding/base64"
	"fmt"
	"html"
	"os"
	"strings"
	"testing"
	"time"

	"github.com/hejmo-home/hejmo/internal/calendar"
	"github.com/hejmo-home/hejmo/internal/familyview"
	"github.com/hejmo-home/hejmo/internal/server"
	"github.com/hejmo-home/hejmo/web"
)

// TestWriteDesignPreview27 writes the self-contained preview page for the
// product owner's approval of ticket 5.7 (portrait layout, column limits).
// Every frame is an iframe with the real stylesheet and the real template, so
// the media query (orientation) and the column minimum act on a true viewport.
// Run: HEJMO_WRITE_PREVIEW=../../docs/design/preview-27.html go test ./internal/server -run WriteDesignPreview27
func TestWriteDesignPreview27(t *testing.T) {
	out := os.Getenv("HEJMO_WRITE_PREVIEW")
	if out == "" {
		t.Skip("set HEJMO_WRITE_PREVIEW to the output path to write the preview")
	}
	css, err := web.Static.ReadFile("static/hejmo.css")
	if err != nil {
		t.Fatal(err)
	}
	font, err := web.Static.ReadFile("static/fonts/Figtree-wght.ttf")
	if err != nil {
		t.Fatal(err)
	}
	style := strings.Replace(string(css), `url("/static/fonts/Figtree-wght.ttf")`, "url(data:font/ttf;base64,"+base64.StdEncoding.EncodeToString(font)+")", 1)

	d := func(day, h, m int) time.Time { return time.Date(2026, 11, day, h, m, 0, 0, berlinTZ) }
	four := []familyview.Person{
		{ID: "mama", Name: "Mama", Slot: 1, Shape: "circle-filled"}, {ID: "papa", Name: "Papa", Slot: 2, Shape: "circle-empty"},
		{ID: "seb", Name: "Sebastian", Slot: 3, Shape: "square-filled"}, {ID: "mia", Name: "Mia", Slot: 4, Shape: "square-empty"}}
	five := append(append([]familyview.Person(nil), four...), familyview.Person{ID: "oma", Name: "Oma", Slot: 5, Shape: "triangle-filled"})
	occ := func(title string, s, e time.Time, who ...string) calendar.Occurrence {
		return calendar.Occurrence{EventID: title, CalendarID: "c", Title: title, Start: s, End: e, People: who}
	}
	occs := []calendar.Occurrence{
		occ("Dentist", d(1, 9, 0), d(1, 10, 0), "mama"),
		occ("Team meeting", d(1, 10, 0), d(1, 11, 0), "papa"),
		occ("Football", d(1, 15, 0), d(1, 16, 30), "seb", "mia"),
		occ("Pick up Mia", d(1, 16, 45), d(1, 17, 15), "papa"),
		occ("Coffee with Mama", d(1, 15, 0), d(1, 16, 0), "oma"),
		occ("Family lunch", d(1, 12, 30), d(1, 14, 0)),
	}
	build := func(people []familyview.Person) familyview.View {
		v := familyview.Build(familyview.Input{Now: d(1, 8, 30), Lang: "en", Region: "DE-BY", People: people, Occurrences: occs})
		v.Columns[0].Progress = &familyview.Progress{Done: 3, Total: 5}
		v.Columns[3].Progress = &familyview.Progress{Done: 2, Total: 2}
		return v
	}

	var body strings.Builder
	frame := func(caption, theme string, w, h int, v familyview.View) {
		view, err := server.RenderFamilyView("en", v)
		if err != nil {
			t.Fatal(err)
		}
		doc := fmt.Sprintf(`<!doctype html><html lang="en" data-theme="%s"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><style>%s</style></head><body><div class="family-page"><div data-view>%s</div></div></body></html>`, theme, style, view)
		fmt.Fprintf(&body, `<figure><figcaption>%s (%dx%d)</figcaption><iframe title="%s" width="%d" height="%d" srcdoc="%s"></iframe></figure>`+"\n", caption, w, h, caption, w, h, html.EscapeString(doc))
	}
	body.WriteString("<h2>Landscape 1024x768, four people (all visible; up to six fit)</h2><div class=\"row\">\n")
	for _, th := range [][2]string{{"Light", "light"}, {"Dark", "dark"}, {"Black and white", "bw"}} {
		frame(th[0], th[1], 1024, 768, build(four))
	}
	body.WriteString("</div><h2>Portrait 768x1024, same four people (rotated: the layout adapts, up to four columns)</h2><div class=\"row\">\n")
	for _, th := range [][2]string{{"Light", "light"}, {"Dark", "dark"}, {"Black and white", "bw"}} {
		frame(th[0], th[1], 768, 1024, build(four))
	}
	body.WriteString("</div><h2>Portrait with a fifth person (the example family plus an extra \"Oma\"): four columns visible, the fifth by scrolling sideways</h2><div class=\"row\">\n")
	frame("iPad portrait", "light", 768, 1024, build(five))
	frame("iPad Air portrait", "light", 820, 1180, build(five))
	frame("Black and white", "bw", 768, 1024, build(five))
	body.WriteString("</div><h2>Phone portrait 375x812, four people: two columns visible (minimum width 144 px), the rest by scrolling</h2><div class=\"row\">\n")
	frame("iPhone portrait", "light", 375, 812, build(four))
	body.WriteString("</div><h2>Phone landscape 812x375, four people with a footer tile: the columns are short, the footer takes its share of the height</h2><div class=\"row\">\n")
	phoneLandscape := build(four)
	phoneLandscape.Meal = &familyview.Tile{Label: "Dinner", Lines: []string{"Pasta bake"}}
	frame("iPhone landscape", "light", 812, 375, phoneLandscape)
	body.WriteString("</div>\n")

	page := `<!doctype html>
<!-- Generated by TestWriteDesignPreview27 from the real view model, template and stylesheet (ticket 5.7). Stylesheet and font are inlined copies of web/static and do not follow later changes. No external requests. -->
<html lang="en"><head><meta charset="utf-8"><title>Hejmo preview 5.7 portrait layout</title>
<style>
body{margin:0;padding:16px;background:#888;font-family:system-ui,sans-serif}
h1,h2{color:#fff}h1{font-size:22px}h2{font-size:18px;margin:20px 0 8px}
figure{margin:0 0 28px}figcaption{color:#fff;margin-bottom:6px;font-weight:700}
.row{display:flex;flex-wrap:wrap;gap:24px;align-items:flex-start}
iframe{border:0;background:#fff;display:block}
</style></head><body>
<h1>Hejmo 5.7 portrait layout and column limits: example family (Mama, Papa, Sebastian, Mia), Sunday 01/11/2026, 08:30</h1>
` + body.String() + `</body></html>
`
	if err := os.WriteFile(out, []byte(page), 0o644); err != nil {
		t.Fatal(err)
	}
}
