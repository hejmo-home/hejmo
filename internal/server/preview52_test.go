package server_test

import (
	"encoding/base64"
	"fmt"
	"os"
	"strings"
	"testing"
	"time"

	"github.com/hejmo-home/hejmo/internal/calendar"
	"github.com/hejmo-home/hejmo/internal/familyview"
	"github.com/hejmo-home/hejmo/internal/i18n"
	"github.com/hejmo-home/hejmo/internal/server"
	"github.com/hejmo-home/hejmo/web"
)

// TestWriteThemePreview writes the self-contained preview page for ticket
// 5.15 (themes by sunrise and sunset): the real family view, rendered with the
// real template for the example family, in each theme a display can show.
// Run: HEJMO_WRITE_PREVIEW_52=$PWD/docs/design/preview-52.html go test ./internal/server -run WriteThemePreview
func TestWriteThemePreview(t *testing.T) {
	out := os.Getenv("HEJMO_WRITE_PREVIEW_52")
	if out == "" {
		t.Skip("set HEJMO_WRITE_PREVIEW_52 to the output path to write the preview")
	}
	css, err := web.Static.ReadFile("static/hejmo.css")
	if err != nil {
		t.Fatal(err)
	}
	font, err := web.Static.ReadFile("static/fonts/Figtree-wght.ttf")
	if err != nil {
		t.Fatal(err)
	}
	style := strings.Replace(string(css), `url("/static/fonts/Figtree-wght.ttf")`, "url(data:font/ttf;base64,"+base64.StdEncoding.EncodeToString(font)+")", 1)

	d := func(day, h, m int) time.Time { return time.Date(2026, 11, day, h, m, 0, 0, berlinTZ) }
	people := []familyview.Person{
		{ID: "mama", Name: "Mama", Slot: 1, Shape: "circle-filled"}, {ID: "papa", Name: "Papa", Slot: 2, Shape: "circle-empty"},
		{ID: "seb", Name: "Sebastian", Slot: 3, Shape: "square-filled"}, {ID: "mia", Name: "Mia", Slot: 4, Shape: "square-empty"}}
	occ := func(title string, s, e time.Time, who ...string) calendar.Occurrence {
		return calendar.Occurrence{EventID: title, CalendarID: "c", Title: title, Start: s, End: e, People: who}
	}
	occs := []calendar.Occurrence{
		occ("Dentist", d(1, 9, 0), d(1, 10, 0), "mama"),
		occ("Team meeting", d(1, 10, 0), d(1, 11, 0), "papa"),
		occ("Football", d(1, 15, 0), d(1, 16, 30), "seb", "mia"),
		occ("Pick up Mia", d(1, 16, 45), d(1, 17, 15), "papa"),
		occ("Family lunch", d(1, 12, 30), d(1, 14, 0)),
	}
	view, err := server.RenderFamilyView("en", familyview.Build(familyview.Input{I18n: i18n.MustLoad(), Now: d(1, 16, 20), Lang: "en", Region: "DE-BY", People: people, Occurrences: occs}))
	if err != nil {
		t.Fatal(err)
	}
	var body strings.Builder
	frame := func(caption, theme string, w, h int) {
		fmt.Fprintf(&body, `<figure><figcaption>%s (%dx%d)</figcaption><div class="frame" data-theme="%s" style="width:%dpx;height:%dpx">%s</div></figure>`+"\n", caption, w, h, theme, w, h, view)
	}
	body.WriteString("<h2>Landscape 1024x768: the three palettes a display switches between</h2><div class=\"row\">\n")
	frame("Light (E-Ink colour, or a normal screen by day)", "light", 1024, 768)
	frame("Dark (a normal screen from sunset to sunrise; also dark on E-Ink)", "dark", 1024, 768)
	frame("Black and white (E-Ink black-and-white, theme light)", "bw", 1024, 768)
	body.WriteString("</div><h2>Portrait 768x1024</h2><div class=\"row\">\n")
	frame("Light", "light", 768, 1024)
	frame("Dark", "dark", 768, 1024)
	frame("Black and white", "bw", 768, 1024)
	body.WriteString(`</div><h2>Display settings in the web interface</h2>
<div class="settings" data-theme="light"><strong>Hallway (normal screen)</strong>
<label>Theme <select><option>Light</option><option>Dark</option><option selected>Automatic (dark from sunset to sunrise)</option></select></label>
<label>Sunrise offset in minutes (-180 to 180) <input type="number" value="45"></label>
<label>Sunset offset in minutes (-180 to 180) <input type="number" value="-30"></label>
<p>Example, Munich on 21/06/2026: sunrise 05:13, sunset 21:17. With these offsets the display turns light at 05:58 and dark at 20:47. Defaults: E-Ink light, normal screen automatic.</p></div>
`)
	page := `<!doctype html>
<!-- Generated by TestWriteThemePreview from the real view model and template (ticket 5.15). The stylesheet and font are inlined copies of web/static and do not follow later changes. -->
<html lang="en"><head><meta charset="utf-8"><title>Hejmo preview 5.15 themes</title>
<style>` + style + `
body{padding:16px;background:#888;font-family:Figtree,system-ui,sans-serif}
body > h1,body > h2{color:#fff}body > h1{font-size:22px}body > h2{font-size:18px;margin:20px 0 8px}
figure{margin:0 0 28px}figcaption{color:#fff;margin-bottom:6px;font-weight:700}
.row{display:flex;flex-wrap:wrap;gap:24px;align-items:flex-start}
.frame{background:var(--background);color:var(--text);padding:var(--margin);overflow:hidden;box-sizing:border-box}
.frame .fv{height:100%}
.settings{background:var(--background);color:var(--text);padding:16px;max-width:640px;display:grid;gap:10px}
.settings label{display:grid;gap:4px}
</style></head><body>
<h1>Hejmo 5.15 themes by sunrise and sunset: preview with the example family (Mama, Papa, Sebastian, Mia)</h1>
` + body.String() + `</body></html>
`
	if err := os.WriteFile(out, []byte(page), 0o644); err != nil {
		t.Fatal(err)
	}
}
