package server_test

import (
	"encoding/base64"
	"fmt"
	"html"
	"os"
	"strings"
	"testing"

	"github.com/hejmo-home/hejmo/internal/server"
	"github.com/hejmo-home/hejmo/web"
)

// TestWriteDesignPreview75 writes the self-contained preview page for the
// product owner's approval of ticket 5.20 (recovery codes, /otp). It renders
// the real templates in en and de; nothing is hand-written HTML.
// Run: HEJMO_WRITE_PREVIEW_75=../../docs/design/preview-75.html go test ./internal/server -run WriteDesignPreview75
func TestWriteDesignPreview75(t *testing.T) {
	out := os.Getenv("HEJMO_WRITE_PREVIEW_75")
	if out == "" {
		t.Skip("set HEJMO_WRITE_PREVIEW_75 to the output path to write the preview")
	}
	css, err := web.Static.ReadFile("static/hejmo.css")
	if err != nil {
		t.Fatal(err)
	}
	font, err := web.Static.ReadFile("static/fonts/Figtree-wght.ttf")
	if err != nil {
		t.Fatal(err)
	}
	style := strings.Replace(string(css), `url("/static/fonts/Figtree-wght.ttf")`, "url(data:font/ttf;base64,"+base64.StdEncoding.EncodeToString(font)+")", 1)

	var body strings.Builder
	shots := []struct{ state, title string }{
		{"form", "/otp: recovery codes left, and reset forms for two other parents (Papa, Oma)"},
		{"error", "/otp: wrong confirmation at Papa's reset form"},
		{"done", "/otp: after resetting Papa (success)"},
		{"codes", "Recovery codes page, shown once after setup or after creating a new set"},
	}
	for _, lang := range []string{"en", "de"} {
		fmt.Fprintf(&body, "<h2>Language: %s</h2><div class=\"row\">\n", lang)
		for _, s := range shots {
			page, err := server.RenderOTPPreview(lang, s.state)
			if err != nil {
				t.Fatal(err)
			}
			page = strings.Replace(page, `<link rel="stylesheet" href="/static/hejmo.css">`, "<style>"+style+"</style>", 1)
			fmt.Fprintf(&body, `<figure><figcaption>%s (%s, 480 px wide)</figcaption><iframe title="%s" srcdoc="%s"></iframe></figure>`+"\n",
				html.EscapeString(s.title), lang, html.EscapeString(s.title), html.EscapeString(page))
		}
		body.WriteString("</div>\n")
	}
	page := `<!doctype html>
<!-- Generated by TestWriteDesignPreview75 from the real templates (ticket 5.20). The stylesheet and font are inlined copies of web/static and do not follow later changes. The shared form patterns of 5.16 (#71) are not merged yet, so the current stylesheet is used. -->
<html lang="en"><head><meta charset="utf-8"><title>Hejmo preview 5.20 recovery codes</title>
<style>body{padding:16px;background:#888;font-family:system-ui,sans-serif}
h1,h2{color:#fff}h1{font-size:22px}h2{font-size:18px;margin:20px 0 8px}
figure{margin:0 0 28px}figcaption{color:#fff;margin-bottom:6px;font-weight:700;max-width:480px}
.row{display:flex;flex-wrap:wrap;gap:24px;align-items:flex-start}
iframe{width:480px;height:900px;border:0;background:#fff}</style></head><body>
<h1>Hejmo 5.20 recovery codes: preview of the real /otp and recovery codes pages (the signed-in parent is Mama; the other parents are Papa and Oma)</h1>
` + body.String() + `</body></html>
`
	if err := os.WriteFile(out, []byte(page), 0o644); err != nil {
		t.Fatal(err)
	}
}
