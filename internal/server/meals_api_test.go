func TestMealScopesLimitATokenToTheMealPlan(t *testing.T) {
	c := signedInAPI(t)
	putMeal(t, c, tuesday, "dinner", "Nudelauflauf")
	read := c.withToken(c.newToken("meals:read"))
	if list := mealsBetween(t, read, tuesday, tuesday); len(list) != 1 {
		t.Fatalf("meals:read sees %v", list)
	}
	if status, _ := putMeal(t, read, tuesday, "dinner", "Pizza"); status != http.StatusForbidden {
		t.Errorf("meals:read put = %d, want 403", status)
	}
	write := c.withToken(c.newToken("meals"))
	if status, _ := putMeal(t, write, tuesday, "dinner", "Pizza"); status != http.StatusOK {
		t.Errorf("meals put = %d, want 200", status)
	}
	if status, _, _ := c.withToken(c.newToken("tasks")).call(http.MethodGet, "/meals", nil); status != http.StatusForbidden {
		t.Errorf("tasks token read meals = %d, want 403", status)
	}
}
